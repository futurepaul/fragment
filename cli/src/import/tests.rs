//! The parsers on small synthetic sessions, one per format and generation,
//! each record shaped as its tool writes it (never a real chat).

use super::*;

fn jsonl(lines: &[Value]) -> impl Iterator<Item = Value> + '_ {
    lines.iter().cloned()
}

fn said(c: &Conversation) -> Vec<(Role, &str)> {
    c.messages.iter().map(|m| (m.role, m.text.as_str())).collect()
}

const T0: &str = "2026-03-01T10:00:00.000Z";
const T0_MS: i64 = 1_772_359_200_000;

fn at(s: i64) -> String {
    let ms = T0_MS + s * 1000;
    let (y, m, d) = fragment_core::cron::civil(ms.div_euclid(86_400_000));
    let t = ms.rem_euclid(86_400_000) / 1000;
    format!("{y:04}-{m:02}-{d:02}T{:02}:{:02}:{:02}.000Z", t / 3600, t / 60 % 60, t % 60)
}

/// Goal: the times every format writes read as one clock. Method: ISO 8601
/// with and without a zone, fractions, offsets, epoch seconds and
/// milliseconds, and malformed ones.
#[test]
fn times_read_as_utc_milliseconds() {
    assert_eq!(parse_time(T0), Some(T0_MS));
    assert_eq!(parse_time("2026-03-01T10:00:00Z"), Some(T0_MS));
    assert_eq!(parse_time("2026-03-01T10:00:00.123456+00:00"), Some(T0_MS + 123));
    assert_eq!(parse_time("2026-03-01T11:30:00+01:30"), Some(T0_MS), "an offset is taken away");
    assert_eq!(parse_time("2026-03-01T05:00:00-0500"), Some(T0_MS));
    assert_eq!(parse_time("2026-03-01 10:00:00.5"), Some(T0_MS + 500), "no zone: UTC");
    assert_eq!(parse_time("2026-03-01"), Some(T0_MS - 10 * 3_600_000));
    assert_eq!(parse_time("1970-01-01T00:00:00Z"), Some(0));
    assert_eq!(parse_time("2000-02-29T00:00:00Z"), Some(951_782_400_000), "a leap day");
    for bad in ["", "2026-3-1", "2026-13-01", "2026-03-01T25:00:00Z", "2026-03-01T10:00:00Q", "2026-03-01T10:00:00.Z", "yesterday"] {
        assert_eq!(parse_time(bad), None, "{bad:?}");
    }
    assert_eq!(time_of(&json!(1_772_359_200.25)), Some(T0_MS + 250), "Hermes's seconds");
    assert_eq!(time_of(&json!(T0_MS)), Some(T0_MS), "Codex's milliseconds");
    assert_eq!(time_of(&json!(-5)), None);
    assert_eq!(at(61), "2026-03-01T10:01:01.000Z");
}

/// Goal: a message the CLI caps is the one the mind logs (its `capText`):
/// head and tail kept, the cut counted. Method: texts at, under and over
/// the cap, in characters, not bytes.
#[test]
fn caps_keep_head_and_tail_as_the_mind_does() {
    let at_cap = "é".repeat(CAP);
    assert_eq!(cap_text(&at_cap, CAP), at_cap, "at the cap, in characters, nothing is cut");
    let long = format!("{}{}", "a".repeat(20_000), "b".repeat(20_000));
    let capped = cap_text(&long, CAP);
    assert_eq!(capped.chars().count() <= CAP, true);
    assert!(capped.starts_with(&"a".repeat(14_960)) && capped.ends_with(&"b".repeat(14_960)));
    assert!(capped.contains("\n\n[… 10080 characters cut here …]\n\n"), "{}", &capped[14_950..15_010]);
}

