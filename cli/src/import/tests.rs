fn conv(source: Source, id: &str, started: i64, messages: &[(Role, &str)]) -> Conversation {
    Conversation {
        source,
        id: id.into(),
        title: None,
        started,
        messages: messages.iter().enumerate().map(|(k, (role, text))| Message { role: *role, text: (*text).into(), at: started + k as i64, key: None }).collect(),
    }
}

