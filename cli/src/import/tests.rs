/// Goal: a session forked from another carries that one's records under its
/// id: they are that conversation's, merged with its own file once.
/// Method: an original and a fork holding a copy of its first turn.
#[test]
fn claude_code_forks_merge_into_their_original() {
    let (a, b) = ("aaaaaaaa-0000-4000-8000-000000000000", "bbbbbbbb-0000-4000-8000-000000000000");
    let rec = |sid: &str, t: i64, kind: &str, text: &str| {
        let content = if kind == "user" { json!(text) } else { json!([{ "type": "text", "text": text }]) };
        json!({ "type": kind, "sessionId": sid, "uuid": format!("{sid}-{t}"), "timestamp": at(t), "message": { "id": format!("m{t}"), "role": kind, "content": content } })
    };
    let original = vec![rec(a, 0, "user", "first question"), rec(a, 1, "assistant", "first answer"), rec(a, 2, "user", "second question"), rec(a, 3, "assistant", "second answer")];
    let fork = vec![rec(a, 0, "user", "first question"), rec(a, 1, "assistant", "first answer"), rec(b, 10, "user", "a fork's own question"), rec(b, 11, "assistant", "its answer")];
    let mut convs = claude_code(b, jsonl(&fork));
    convs.extend(claude_code(a, jsonl(&original)));
    assert_eq!(convs.iter().map(|c| c.id.as_str()).collect::<Vec<_>>(), [a, b, a], "the fork's file holds two conversations");
    let ready = prepare(convs, None, None);
    assert_eq!(ready.len(), 2);
    assert_eq!(said(&ready[0]).len(), 4, "the original once, its copy merged away: {:?}", said(&ready[0]));
    assert_eq!(said(&ready[1]), [(Role::User, "a fork's own question"), (Role::Assistant, "its answer")]);
}

